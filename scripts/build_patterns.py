def claim_section(label, title, text, items, icon_name, anchor):
    """Split heading on white, followed by the cards on a grey section (as in the Elementor/Mockup layout)."""
    cards = grid(join(*[card(join(icon(icon_name, tone=TONES[k]), heading(t, 3), p(x))) for k, (t, x) in enumerate(items)]),
                 columns=2, min_width="20rem")
    return join(split(label, title, [text], anchor=anchor), section(cards, variation="section-mist"))


