def write(slug, title, category, markup, extra=""):
    header = (f"<?php\n/**\n * Title: {title}\n * Slug: appa/{slug}\n * Categories: {category}\n{extra}"
              f" *\n * {GENERATED}\n *\n * @package BW\\AppaTheme\n */\n\ndeclare(strict_types=1);\n?>\n")
    (OUT / f"{slug}.php").write_text(header + markup + "\n", "utf-8")


def main():
    for f in OUT.glob("*.php"):
        if GENERATED in f.read_text("utf-8"):
            f.unlink()
    for slug, (title, markup) in SECTIONS.items():
        write(slug, title, "appa", markup)
    for slug, (title, parts) in PAGES.items():
        write(f"page-{slug}", title, "appa-pages", join(*[SECTIONS[s][1] for s in parts]),
              " * Block Types: core/post-content\n * Post Types: page\n * Inserter: yes\n")
    print(f"-> {len(SECTIONS)} sections, {len(PAGES)} pages in {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
