# ── Reusable section builders ───────────────────────────────────────────────

def split(label, title, body, link=None, *, anchor=None, variation=None, heading_level=2):
    """Eyebrow + heading in a narrow left column, text (and an optional arrow link) on the right."""
    left = join(eyebrow(label), heading(title, heading_level))
    right = join(*[p(t) if not t.startswith("<!--") else t for t in body], arrow(*link) if link else "")
    return section(columns(left, right, widths=["33.33%", "66.66%"]), anchor=anchor, variation=variation)


def page_header(label, title, lead=None, jump=None, photo=None):
    """Page header: sky band with eyebrow, H1 and lead – or a photo band with the title in a white box."""
    inner = join(eyebrow(label), heading(title, 1), p(lead, variation="lead") if lead else "")
    if photo:
        out = cover(asset(photo), group(inner, cls="bw-page-photo__box", gap="1", layout={"type": "default"}),
                    cls="bw-page-photo")
    else:
        out = section(stack(inner, gap="3"), variation="section-sky", cls="bw-page-header", pad=("16", "16"))
    if jump:
        items = "".join(f'<li><a href="#{a}">{t}</a></li>' for t, a in jump)
        nav = (f'<!-- wp:html -->\n<nav aria-label="Auf dieser Seite"><ul class="bw-jump-nav">{items}</ul></nav>\n'
               f'<!-- /wp:html -->')
        out = join(out, section(nav, variation="section-sky", cls="bw-jump-band", pad=("4", "4")))
    return out


def cta(title, text, label, link, *, eyebrow_text=None, variation="section-green", button_style=None, gap="2"):
    """Call to action band: text on the left, button on the right (below on small screens)."""
    left = join(eyebrow(eyebrow_text) if eyebrow_text else "", heading(title, 2, size="xx-large"), p(text))
    return section(row(join(stack(left, gap=gap), buttons(button(label, link, button_style))), cls="bw-cta__row"),
                   variation=variation, pad=("12", "12"))


def icon_card(icon_name, tone, title, text, link=None):
    return card(join(icon(icon_name, tone=tone), heading(title, 3), p(text), arrow(*link) if link else ""))


def card_grid(cards, columns_=3, variation=None, pad=("section", "section"), anchor=None, cls=None):
    return section(grid(join(*cards), columns=columns_, cls=cls), variation=variation, pad=pad, anchor=anchor)


def events_query(per_page, *, archive=False, title_level=3):
    """Query loop for upcoming events (post type appa_event of the bw-appa plugin)."""
    query = {"perPage": per_page, "pages": 0, "offset": 0, "postType": "appa_event", "order": "asc",
             "orderBy": "date", "inherit": archive}
    import json
    q = json.dumps({"queryId": 7, "query": query, "layout": {"type": "default"}}, ensure_ascii=False,
                   separators=(",", ":"))
    when = ('<!-- wp:paragraph {"metadata":{"bindings":{"content":{"source":"bw-appa/event","args":{"key":"when"}}}},'
            '"className":"is-style-eyebrow"} -->\n<p class="is-style-eyebrow"></p>\n<!-- /wp:paragraph -->')
    access = ('<!-- wp:paragraph {"metadata":{"bindings":{"content":{"source":"bw-appa/event","args":{"key":"access"}}}},'
              '"fontSize":"sm"} -->\n<p class="has-sm-font-size"></p>\n<!-- /wp:paragraph -->')
    title = f'<!-- wp:post-title {{"level":{title_level},"isLink":true,"fontSize":"xl"}} /-->'
    excerpt = '<!-- wp:post-excerpt {"excerptLength":40} /-->'
    zoom = buttons(button("Per Zoom teilnehmen", None,
                          bindings={"url": {"source": "bw-appa/event", "args": {"key": "zoom_link"}}}))
    item = card(join(when, title, excerpt, access, zoom))
    empty = p("Aktuell sind keine Termine geplant. Sobald es Neuigkeiten gibt, findest du sie hier.")
    tpl = ('<!-- wp:post-template {"layout":{"type":"grid","columnCount":2,"minimumColumnWidth":"20rem"}} -->\n'
           f"{item}\n<!-- /wp:post-template -->")
    no = f"<!-- wp:query-no-results -->\n{card(empty, variation='card-flat')}\n<!-- /wp:query-no-results -->"
    return f"<!-- wp:query {q} -->\n<div class=\"wp-block-query\">\n{tpl}\n\n{no}\n</div>\n<!-- /wp:query -->"


def form_block(form):
    return f'<!-- wp:bw-appa/form {{"form":"{form}"}} /-->'


